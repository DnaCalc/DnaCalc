/// Measured dynamic-array file form for a named Excel function.
pub struct FunctionFileForm {
    pub name: &'static str,
    pub first_count: usize,
    pub bases: &'static [bool],
    pub positions: &'static [bool],
}

/// File-form measurements for an invariant, upper-case function name.
pub fn file_form(name: &str) -> Option<&'static FunctionFileForm> {
    file_form_table::FUNCTIONS.binary_search_by(|entry| entry.name.as_bytes().cmp(name.as_bytes()))
        .ok().map(|i| &file_form_table::FUNCTIONS[i])
}

/// Prefix measured for an invariant, upper-case function name.
pub fn file_prefix(name: &str) -> Option<FilePrefix> {
    FILE_PREFIXES.binary_search_by(|(n, _, _)| n.as_bytes().cmp(name.as_bytes()))
        .ok().map(|i| FILE_PREFIXES[i].1)
}

/// Prefix from the original executable catalogue declaration.
pub fn executable_file_prefix(name: &str) -> Option<FilePrefix> {
    FILE_PREFIXES.binary_search_by(|(n, _, _)| n.as_bytes().cmp(name.as_bytes()))
        .ok().and_then(|i| FILE_PREFIXES[i].2.then_some(FILE_PREFIXES[i].1))
}

