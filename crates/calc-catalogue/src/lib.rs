//! Shared, measured Excel function file prefixes.
//!
//! The two former tables overlap but are not identical: the codec also has entries for names
//! outside the executable catalogue, and the executable catalogue has later measured entries.

/// Prefix used for functions added after the original file format.
pub const FUTURE_FUNCTION_PREFIX: &str = "_xlfn.";
/// Additional prefix used for worksheet-only functions.
pub const WORKSHEET_FUNCTION_PREFIX: &str = "_xlws.";
/// Prefix preserving a user-defined call that collides with a built-in name.
pub const USER_DEFINED_FUNCTION_PREFIX: &str = "_xludf.";

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum FilePrefix { Bare, Xlfn, XlfnXlws }

impl FilePrefix {
    pub const fn text(self) -> &'static str {
        match self { Self::Bare => "", Self::Xlfn => FUTURE_FUNCTION_PREFIX, Self::XlfnXlws => "_xlfn._xlws." }
    }
}

