#[cfg(test)]
mod tests {
    use super::*;

    // These are snapshots of both original declarations, not regenerated Excel answers.
    #[cfg_attr(not(target_arch = "wasm32"), test)]
    #[cfg_attr(target_arch = "wasm32", wasm_bindgen_test::wasm_bindgen_test)]
    fn old_declarations_match() {
        for (fixture, count) in [(include_str!("../tests/fixtures/func-prefixes.tsv"), 515),
                                 (include_str!("../tests/fixtures/doc-prefixes.tsv"), 517)] {
            let mut previous = "";
            assert_eq!(fixture.lines().count(), count);
            for line in fixture.lines() {
                let (name, expected) = line.split_once('\t').unwrap();
                assert!(previous < name);
                previous = name;
                assert_eq!(format!("{:?}", file_prefix(name).unwrap()), expected, "{name}");
            }
        }
        let old_func = include_str!("../tests/fixtures/func-prefixes.tsv");
        for (name, prefix, _) in FILE_PREFIXES {
            let expected = old_func.lines().find_map(|line| {
                let (old_name, old_prefix) = line.split_once('\t').unwrap();
                (old_name == *name).then_some(old_prefix)
            });
            assert_eq!(executable_file_prefix(name), expected.map(|_| *prefix), "{name}");
        }
        assert_eq!(FILE_PREFIXES.len(), 523);
        assert!(FILE_PREFIXES.windows(2).all(|w| w[0].0 < w[1].0));
    }
}
