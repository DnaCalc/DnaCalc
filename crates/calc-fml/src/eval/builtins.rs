/// Whether `name` (any ASCII case, without a file prefix) is an Excel built-in function.
pub(crate) fn is_builtin(name: &str) -> bool {
    let upper = name.to_ascii_uppercase();
    NAMES.binary_search(&upper.as_str()).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[cfg_attr(not(target_arch = "wasm32"), test)]
    #[cfg_attr(target_arch = "wasm32", wasm_bindgen_test::wasm_bindgen_test)]
    fn names_are_sorted_and_found_in_any_case() {
        assert!(NAMES.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(is_builtin("gcd") && is_builtin("Sum") && is_builtin("STDEV.P"));
        assert!(!is_builtin("zzgcd") && !is_builtin("TaxRate"));
    }
}
